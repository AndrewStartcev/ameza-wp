/**
 * Runs after pages.php has created draft pages. Does not overwrite real content
 * or change a page's publish status.
 */
function ameza_fill_empty_legal_pages(): void {
    if (!is_admin() || !current_user_can('manage_options')) { return; }
    foreach (ameza_legal_document_templates() as $slug => $html) {
        $page = get_page_by_path($slug, OBJECT, 'page');
        if (!$page instanceof WP_Post || $page->post_status === 'trash' ||
            trim((string)$page->post_content) !== '') {
            continue;
        }
        wp_update_post([
            'ID' => $page->ID,
            'post_content' => wp_kses_post($html),
        ]);
    }
}
add_action('admin_init', 'ameza_fill_empty_legal_pages', 80);
